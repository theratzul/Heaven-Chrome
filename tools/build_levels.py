# Helper to build a level
def build_lvl(walls=[], platforms=[], hazards=[], exit_pos=(28, 4)):
    g = empty_grid()
    # Starting base platform
    for x in range(1, 5):
        g[22][x] = 2
    # Custom walls
    for (x, y, w, h) in walls:
        for dy in range(h):
            for dx in range(w):
                if 0 < x+dx < 31 and 0 < y+dy < 23:
                    g[y+dy][x+dx] = 1
    # Custom platforms
    for (x, y, w) in platforms:
        for dx in range(w):
            if 0 < x+dx < 31 and 0 < y < 23:
                g[y][x+dx] = 2
    # Custom hazards
    for (x, y, w, h) in hazards:
        for dy in range(h):
            for dx in range(w):
                if 0 < x+dx < 31 and 0 < y+dy < 23:
                    g[y+dy][x+dx] = 3
    # Exit & platform under exit
    ex, ey = exit_pos
    g[ey][ex] = 4
    if ey + 1 < 23 and g[ey+1][ex] == 0:
        for dx in (-1, 0, 1):
            if 0 < ex+dx < 31:
                g[ey+1][ex+dx] = 2
    # Ensure start (2, 20) and immediate surroundings are clear
    g[20][2] = 0
    g[21][2] = 0
    g[20][1] = 0
    g[20][3] = 0
    return g

